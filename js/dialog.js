export function parseIntent(text, residents, self) {
  const t = text.replace(/\s+/g, '').replace(/[!！]+/g, '！');
  const r = { kind: 'unknown', text: t };
  const q = /[?？]$|(か|の|かな|っけ|なに|何|なん)[？?]?$/.test(t);
  r.question = q;
  // 住民の名前
  const others = residents.filter((o) => t.includes(o.name));
  r.target = others.find((o) => o !== self) || null;
  r.self = others.includes(self);
  // 場所
  for (const [id, re] of PLACE_WORDS) if (re.test(t)) { r.place = id; break; }
  if (!r.place) for (const [id, re] of IMPLIED_PLACE) if (re.test(t)) { r.place = id; r.implied = true; break; }

  if (/^(じゃあね|じゃあな|またね|またな|さようなら|さよなら|バイバイ|ばいばい|また今度|おやすみ|失礼します|では、?また)/.test(t)) return { ...r, kind: 'bye' };
  if (/(好きです|愛して|あいして|結婚し|けっこんし|付き合ってください|つきあってください|恋人に)/.test(t)) return { ...r, kind: 'love' };
  if (THREAT.test(t)) return { ...r, kind: 'threat' };
  if (!r.target && /(俺|僕|ぼく|私|わたし|あたし|オレ|自分)(の|って|は|が)(こと)?(を)?(どう|好き|嫌い|信用|どんな)/.test(t)) return { ...r, kind: 'opinionMe' };
  if (RUDE.test(t) && !r.target) return { ...r, kind: 'insult' };
  if (/(ごめん|すまない|すまん|すみません|悪かった|申し訳)/.test(t)) return { ...r, kind: 'apology' };
  if (YES.test(t) && t.length <= 14) return { ...r, kind: 'yes' };
  if (NO.test(t) && t.length <= 14) return { ...r, kind: 'no' };
  if (DISMISS.test(t)) return { ...r, kind: 'dismiss' };
  if (/(ありがと|感謝|助かった|助かる|サンキュー)/.test(t)) return { ...r, kind: 'thanks' };
  // 誘う
  const treat = TREAT_GIVE.test(t);
  if (treat && !r.place) return { ...r, kind: 'invite', place: 'diner', treat: true };
  if (r.place && (INVITE.test(t) || treat) && !/(どこ|場所|行き方|どっち|ある[？?]?$)/.test(t)) return { ...r, kind: 'invite', treat };
  if (FOLLOW.test(t)) return { ...r, kind: 'invite', place: null };
  if (/(見逃|内緒|ないしょ|黙って|だまって|秘密|ひみつ)/.test(t)) return { ...r, kind: 'secret' };
  if (TREAT_ASK.test(t)) return { ...r, kind: 'askMoney' };
  if (/(金|かね|コイン|お金|おかね|\dG|G)/.test(t) && ASK.test(t)) return { ...r, kind: 'askMoney' };
  if (/(食べ物|たべもの|ご飯|ごはん|食料|しょくりょう|パン|飯|めし|野菜)/.test(t) && ASK.test(t)) return { ...r, kind: 'askFood' };
  // 人について
  if (r.target) {
    if (/(どこ|居場所|見かけ|見なかった)/.test(t)) return { ...r, kind: 'whereIs' };
    if (NEG.test(t) && !/(どう思|どんな)/.test(t)) return { ...r, kind: 'gossip', neg: true };
    if (POS.test(t) && !/(どう思|どんな)/.test(t)) return { ...r, kind: 'gossip', neg: false };
    return { ...r, kind: 'opinion' };
  }
  if (r.place && /(どこ|場所|行き方|どっち|どうやって行|ある[？?]?$|って何|ってなに)/.test(t)) return { ...r, kind: 'whereIsPlace' };
  if (/(石|隕石|いんせき|物質|光る)/.test(t)) return { ...r, kind: 'meteor' };
  if (/(仕事|しごと|働き|はたらき|働く|はたらく|雇|やと|職|稼|かせ|バイト)/.test(t) && !/(何して|なにして)/.test(t)) return { ...r, kind: 'job' };
  if (/(何して|なにして|何やって|なにやって|何してる|どこ行く|どこいく|どこへ|予定|これから|今日は何)/.test(t)) return { ...r, kind: 'doing' };
  if (/(元気|げんき|調子|ちょうし|大丈夫|だいじょうぶ|疲れ|つかれ|具合|体調|お腹|おなか|腹減|はらへ|食べた[？?]|食べてる)/.test(t)) return { ...r, kind: 'howareyou' };
  if (/(名前|なまえ|誰|だれ|何者|なにもの|自己紹介|はじめまして|初めまして)/.test(t)) return { ...r, kind: 'intro' };
  if (/(趣味|しゅみ|好きな|好物|こうぶつ|好きなもの)/.test(t)) return { ...r, kind: 'likes' };
  if (/(噂|うわさ|何かあった|なにかあった|なんかあった|ニュース|事件|最近|さいきん|変わったこと)/.test(t)) return { ...r, kind: 'rumor' };
  if (/(この町|この街|町のこと|町について|この村|ナリユキ)/.test(t)) return { ...r, kind: 'town' };
  if (/(天気|てんき|暑い|あつい|寒い|さむい|晴れ|雨|日照り)/.test(t)) return { ...r, kind: 'weather' };
  if (/(手伝|てつだ|困って|こまって|助けよう|助けたい|力になる|何かできる|なにかできる)/.test(t)) return { ...r, kind: 'help' };
  if (NICE.test(t)) return { ...r, kind: 'compliment' };
  if (/(こんにちは|こんちは|こんばんは|おはよう|やあ|よう|どうも|ハロー|はろー|ちーっす|こんにちわ|もしもし)/.test(t)) return { ...r, kind: 'greet' };
  if (RUDE.test(t)) return { ...r, kind: 'insult' };
  if (/(教えて|おしえて|って何|ってなに|とは|知ってる|しってる|わかる|分かる|どう思う|なぜ|なんで|どうして)/.test(t)) return { ...r, kind: 'question' };
  return { ...r, kind: q ? 'question' : 'unknown' };
}

