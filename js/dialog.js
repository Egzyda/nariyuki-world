export function fill(s, c, vars = {}) {
  const t = toneOf(c);
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    if (k === 'I') return firstPerson(c);
    if (k === 'you') return t.you;
    if (k === 'name') return c.name;
    return vars[k] ?? '';
  });
}

export function line(c, key, vars = {}, rand = Math.random) {
  const t = toneOf(c);
  let s;
  if (L[key]) {
    const arr = L[key][c.tone] || L[key].cheerful;
    s = arr[Math.floor(rand() * arr.length)];
  } else {
    let pair = N[key];
    if (vars.sub != null) pair = pair[vars.sub] ?? pair.other;
    s = pair[t.pol ? 1 : 0];
  }
  return fill(s, c, vars);
}

